#!/usr/bin/env bash
# Build nikon-firmware-tools' Emulator (no Ant needed) plus K5ParseHarness, then
# run the harness:  tools/fremu/build.sh [token ...]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
nft="$root/tools/nikon-firmware-tools"
emu="$nft/Java/Emulator"
out=${FREMU_OUT:-/tmp/fremu}

[ -d "$nft" ] || git clone --depth 1 https://github.com/simeonpilgrim/nikon-firmware-tools "$nft"

if [ ! -f "$out/classes/com/nikonhacker/emu/FrEmulator.class" ]; then
    mkdir -p "$out/classes" "$out/gen/com/nikonhacker"
    # ApplicationInfo is normally generated by Ant from this template.
    sed 's/@[A-Za-z_.]*@/fremu/g' "$emu/src/template/com/nikonhacker/ApplicationInfo.java" \
        > "$out/gen/com/nikonhacker/ApplicationInfo.java"
    { find "$emu/src/main" -name '*.java'; echo "$out/gen/com/nikonhacker/ApplicationInfo.java"; } > "$out/srcs.txt"
    javac -nowarn -encoding UTF-8 -source 8 -target 8 -cp "$emu/lib/*" -d "$out/classes" @"$out/srcs.txt"
    # Resources (instruction tables, icons) live next to the sources.
    (cd "$emu/src/main" && find . -type f ! -name '*.java' -exec cp --parents {} "$out/classes" \;)
fi

mkdir -p "$out/harness"
javac -nowarn -cp "$out/classes:$emu/lib/*" -d "$out/harness" "$here/K5ParseHarness.java"

if [ $# -gt 0 ]; then
    java -cp "$out/harness:$out/classes:$emu/lib/*" K5ParseHarness "$root/fw/fwdc218b_dec.bin" "$@"
fi
