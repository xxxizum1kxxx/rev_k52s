#!/usr/bin/env python3
"""Build the SD-card files that drive the K-5 IIs factory script mode.

  make_debug_card.py write <sd-root> --preset enable
  make_debug_card.py write <sd-root> --cmd "CAM_LOG_DISP"
  make_debug_card.py check <sd-root>/00077681.541 [--emulate]
  make_debug_card.py presets

The script file name comes from the firmware header (0x14 = script id,
0x10 = model code).  On the K-5 IIs DEVELOP.MOD is only fs_stat'ed
(ScriptMode_files_present, 0x1060F57A); we still write the 10 bytes that the
GR IV / GR IIIx factory entry requires, so the card also works if some build
checks the content.  Lines MUST end in CRLF:
the firmware's script_readline (0x10616BDA) splits on '\\r' and skips one byte.
Only one "exclusive" action (dumps, clears, firmware ops) runs per power-on.
"""
import argparse
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FW = ROOT / "fw" / "fwdc218b.bin"

FLAG_CMDS = {
    "DEBUG_MODE EN", "DEBUG_MODE DIS", "CFDOOR_OPEN EN", "CFDOOR_OPEN DIS",
    "SCRIPT_EN_MODE EN", "SCRIPT_EN_MODE DIS", "SW_DEBUG_MENU EN", "SW_DEBUG_MENU DIS",
    "LIVE_VIEW_TEST_MODE EN", "LIVE_VIEW_TEST_MODE DIS",
}
READONLY_CMDS = {
    "SWITCH_TEST", "DISPLAY_TEST", "MEMORY_TEST", "LENS_COMUNICATION_CHECK",
    "CPU_ADJ_CSV_READ", "CPU_TST_CSV_READ", "CPU_ROM_STORE", "DSP_ROM_STORE", "AF_PINT_DISP",
    "SI_ALL_ON", "CPU_ADJ_DAT_READ", "DSP_ADJ_DAT_READ", "ALL_ADJ_DAT_READ", "DSP_USR_DAT_READ",
    "LENSROM_STORE", "OPEN_DEBUG_MENU", "DISP_REGION_CODE", "CAM_LOG_DAT_READ", "CAM_LOG_DISP",
}
DANGEROUS_CMDS = {
    "WRITE_CF_VNDR EN", "WRITE_CF_VNDR DIS", "USR_DAT_CLEAR", "RELEASE_AGING",
    "CPU_ADJ_FLG_CLEAR", "CPU_ADJ_CSV_WRITE", "CPU_TST_CSV_WRITE", "ICCD_PINT_OFF_CLEAR",
    "COLOR_PINT_COR_CLEAR", "CPU_ADJ_DAT_WRITE", "DSP_ADJ_DAT_WRITE", "DSP_USR_DAT_WRITE",
    "SR_BULB", "DIS_AF_F28", "ONLY_AF_F28", "VLENS_CTRL", "LENS_CPU_FIRMUP", "LENSROM_LOAD",
    "USR_CLEAR_CAM_DISP", "CRE_RECOVERY_FW", "G200_TEST",
    *(f"REGION_CODE {i}" for i in range(6)),
}
KNOWN = FLAG_CMDS | READONLY_CMDS | DANGEROUS_CMDS

DEVELOP_MOD = bytes.fromhex("07012c1f10031e16052d")

PRESETS = {
    "enable": ["DEBUG_MODE EN", "SW_DEBUG_MENU EN"],
    "disable": ["DEBUG_MODE DIS", "SW_DEBUG_MENU DIS", "SCRIPT_EN_MODE DIS"],
    "devmenu": ["OPEN_DEBUG_MENU"],
    "camlog": ["CAM_LOG_DISP"],
    "backup-cpu-rom": ["CPU_ROM_STORE"],
    "backup-dsp-rom": ["DSP_ROM_STORE"],
    "backup-adj": ["ALL_ADJ_DAT_READ"],
    "backup-camlog": ["CAM_LOG_DAT_READ"],
}


K5IIS_107_SCRIPT = "00077681.541"


def script_name(fw=FW):
    if not fw.exists():
        return K5IIS_107_SCRIPT
    hdr = fw.read_bytes()[:0x20]
    model, script_id = struct.unpack(">II", hdr[0x10:0x18])
    return f"{script_id:08d}.{model:03d}"


def firmware_tokens(data: bytes):
    """Port of ScriptMode_load_script + script_readline tokenisation."""
    text = data.split(b"\0", 1)[0]
    pos, toks = 0, []
    while True:
        line = bytearray()
        i = 0
        while pos + i < len(text):
            c = text[pos + i]
            if c == 0x0D:
                i += 2
                break
            line.append(c)
            i += 1
        if not line and i == 0:
            break
        if len(line) >= 0x400:
            raise ValueError(f"line at byte {pos} is {len(line)} bytes; firmware buffer is 0x400")
        pos += i
        j = 0
        while j < len(line):
            c = line[j]
            if c == ord("["):
                end = line.find(b"]", j + 1)
                if end < 0:
                    break
                tok = bytes(line[j + 1:end])
                if len(tok) >= 0x80:
                    raise ValueError(f"token too long: {tok[:40]!r}")
                toks.append(tok.decode("ascii", "replace"))
                j = end + 1
                continue
            if c in (ord("!"), ord(";")):
                break
            j += 1
        if not line:
            continue
    return toks


def build(cmds, allow_dangerous=False):
    lines = ["; K-5 IIs factory script, generated by tools/make_debug_card.py"]
    for c in cmds:
        if c not in KNOWN:
            raise SystemExit(f"unknown command {c!r} (firmware would silently ignore it)")
        if c in DANGEROUS_CMDS and not allow_dangerous:
            raise SystemExit(f"{c!r} is destructive/irreversible; pass --allow-dangerous to emit it")
        lines.append(f"[{c}]")
    data = ("\r\n".join(lines) + "\r\n").encode("ascii")
    assert firmware_tokens(data) == list(cmds), "self-check: tokeniser mismatch"
    return data


def cmd_write(a):
    cmds = PRESETS[a.preset] if a.preset else a.cmd
    if not cmds:
        raise SystemExit("need --preset or --cmd")
    exclusive = [c for c in cmds if c not in FLAG_CMDS]
    if len(exclusive) > 1:
        print(f"warning: only one of {exclusive} will run per power-on", file=sys.stderr)
    data = build(cmds, a.allow_dangerous)
    root = pathlib.Path(a.sd_root)
    root.mkdir(parents=True, exist_ok=True)
    (root / script_name()).write_bytes(data)
    (root / "DEVELOP.MOD").write_bytes(DEVELOP_MOD)
    print(f"wrote {root / script_name()} ({len(data)} bytes) and {root / 'DEVELOP.MOD'}")
    for c in cmds:
        print(f"  [{c}]")


def cmd_check(a):
    toks = firmware_tokens(pathlib.Path(a.file).read_bytes())
    for t in toks:
        kind = ("flag" if t in FLAG_CMDS else "read-only" if t in READONLY_CMDS
                else "DANGEROUS" if t in DANGEROUS_CMDS else "IGNORED (unknown)")
        print(f"  [{t}]  {kind}")
    if a.emulate:
        sys.path.insert(0, str(ROOT / "tools"))
        import emulate_parse
        for r in emulate_parse.emulate(toks):
            print(f"  emu {r['token']!r}: ret={r['ret']} slots={r['slots'] or '-'}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="op", required=True)
    w = sub.add_parser("write")
    w.add_argument("sd_root")
    w.add_argument("--preset", choices=PRESETS)
    w.add_argument("--cmd", action="append", default=[])
    w.add_argument("--allow-dangerous", action="store_true")
    c = sub.add_parser("check")
    c.add_argument("file")
    c.add_argument("--emulate", action="store_true")
    sub.add_parser("presets")
    a = p.parse_args()
    if a.op == "write":
        cmd_write(a)
    elif a.op == "check":
        cmd_check(a)
    else:
        for k, v in PRESETS.items():
            print(f"{k:16} {' '.join(f'[{x}]' for x in v)}")


if __name__ == "__main__":
    main()
